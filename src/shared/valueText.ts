/**
 * "值 ↔ 文本"的通用口径类型.
 *
 * 它刻意是**一个对象**而不是两个并列的回调:口径要能整体传递 -- 同一个 `text`
 * 交给数字框,系数滑块与读数行,三处文本才会逐字符相同.拆成两个函数参数,调用点就
 * 又变成"三处各记一套"(那正是这个库原先的样子,见 `shared/numberText.ts` 的文件头).
 *
 * 与具体类型无关,所以单独一个文件:`numberText` 是它在数值上的实现,`ValueDisplay`
 * 是它(的单向半边)在只读显示上的消费者,两边都从这里取类型,谁也不用认识谁.
 *
 * 两个字段的分工是硬约定:
 * - `toText` **必须是纯函数**:同一输入永远同一输出,不读环境,不读状态
 *   (所以不用 `Intl` -- 它的输出随 ICU 与区域设置变,库的默认行为不该随环境变);
 * - `fromText` **不许抛也不许猜**:读不出来就 `null`,由调用方决定回退策略.
 */

/** 值 -> 文本的**单向**口径:只读显示件用这个就够(不需要把文本读回值). */
export interface ValueTextSource<T> {
    /** 值 -> 文本. */
    toText(value: T): string;
}

/** 值 ↔ 文本的**双向**口径:能编辑的控件要这个. */
export interface ValueText<T> extends ValueTextSource<T> {
    /** 文本 -> 值;不可解析返回 `null`(不抛,不猜). */
    fromText(text: string): T | null;
}
